import asyncio, subprocess
from h2 import *
def code_for(no):
    return subprocess.run(['psql','-h','127.0.0.1','-p','5433','-U','postgres','mms','-Atc',f"select happy_code from service_requests where ticket_no='{no}'"],capture_output=True,text=True).stdout.strip()
async def login_ui(p, phone):
    await p.goto(BASE + '/'); await p.wait_for_timeout(1500)
    await p.get_by_placeholder('10-digit mobile').fill(phone); await p.get_by_role('button', name='Send OTP on WhatsApp').click(); await p.wait_for_timeout(500)
    c = re.search(r'(\d{4})', await p.locator('.banner.warn').inner_text()).group(1)
    await p.locator('input[maxlength="8"]').fill(c); await p.get_by_role('button', name='Log in').click(); await p.wait_for_timeout(1500)
async def main():
    async with async_playwright() as pw:
        b = await launch(pw); p = await new_page(b)
        await login_ui(p, '9000000001')
        await p.goto(BASE + '/#support'); await p.wait_for_timeout(1000)
        print('desk rows:', await p.locator('tbody tr').count())
        await p.get_by_role('button', name='New complaint').click(); await p.wait_for_timeout(300)
        dlg = p.locator('[aria-label="New complaint"]')
        await dlg.locator('select').first.select_option(index=1)
        await dlg.get_by_placeholder(re.compile('Wardrobe door hinge')).fill('Kitchen drawer channel broken')
        await dlg.get_by_role('button', name='Register complaint').click(); await p.wait_for_timeout(1200)
        row = p.locator('tbody tr', has_text='Kitchen drawer channel broken')
        no = (await row.locator('b.mono').inner_text()).strip(); print('ticket:', no)
        await row.click(); await p.wait_for_timeout(500)
        d = p.locator('aside.drawer')
        opts = await d.locator('select').first.locator('option').all_inner_texts(); await d.locator('select').first.select_option(label=[o for o in opts if o.startswith('Ravi')][0])
        await p.wait_for_timeout(900)
        await d.locator('input[type=date]').fill('2099-01-05'); await p.wait_for_timeout(1000)
        print('status after schedule:', await d.locator('h4 .pill').first.inner_text())
        await d.get_by_placeholder(re.compile('What was done')).fill('Replaced channel')
        await d.get_by_role('button', name='Work done').click(); await p.wait_for_timeout(900)
        await d.get_by_placeholder('Happy code').fill('0000'); await d.get_by_role('button', name='Close with happy code').click(); await p.wait_for_timeout(800)
        print('wrong code toast:', await p.get_by_text('does not match').count())
        await p.screenshot(path='/tmp/v18_drawer.png')
        await d.get_by_placeholder('Happy code').fill(code_for(no)); await d.get_by_role('button', name='Close with happy code').click(); await p.wait_for_timeout(1000)
        await p.get_by_role('button', name='Closed').first.click(); await p.wait_for_timeout(400)
        print('closed list has it:', await p.locator('tbody tr', has_text=no).count(), [e for e in p.errs if '401' not in e and 'ERR_FAILED' not in e])
        await p.screenshot(path='/tmp/v18_desk.png')
        # customer app preview: raise
        await p.goto(BASE + '/#customer'); await p.wait_for_timeout(900)
        await p.locator('.mcard').first.click(); await p.wait_for_timeout(900)
        await p.get_by_text('Complaints and service').click(); await p.wait_for_timeout(400)
        await p.get_by_role('button', name='Raise a complaint').click(); await p.wait_for_timeout(300)
