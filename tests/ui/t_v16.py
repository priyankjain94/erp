import asyncio
from h2 import *
async def main():
    async with async_playwright() as pw:
        b = await launch(pw); p = await new_page(b)
        await p.goto(BASE + '/'); await p.wait_for_timeout(1200)
        await p.get_by_role('button', name='Request access').click(); await p.wait_for_timeout(300)
        await p.get_by_label('Your name').fill('Test Joiner'); await p.get_by_label('WhatsApp number').fill('9855500111')
        await p.get_by_label('Your work').select_option('Designer')
        await p.locator('form').get_by_role('button', name='Request access').click(); await p.wait_for_timeout(800)
        print('sent:', await p.get_by_text('Your request has reached the admin').count())
        await p.screenshot(path='/tmp/v16_req.png')
        await p.get_by_role('button', name='Back to login').click()
        await p.get_by_placeholder('10-digit mobile').fill('9000000001'); await p.get_by_role('button', name='Send OTP on WhatsApp').click(); await p.wait_for_timeout(500)
        t = await p.locator('.banner.warn').inner_text(); code = re.search(r'(\d{4})', t).group(1)
        await p.locator('input[maxlength="8"]').fill(code); await p.get_by_role('button', name='Log in').click(); await p.wait_for_timeout(1500)
        await p.goto(BASE + '/#users'); await p.wait_for_timeout(900)
        print('requests box:', await p.get_by_text(re.compile('Access requests · 1 waiting')).count())
        await p.locator('tr', has_text='Test Joiner').get_by_role('button', name='Approve').click(); await p.wait_for_timeout(900)
        print('approved user row:', await p.locator('tbody tr', has_text='Test Joiner').count())
        await p.locator('.seg button', has_text='Company profile').click(); await p.wait_for_timeout(600)
        print('start fresh panel:', await p.get_by_text('Start fresh', exact=True).count())
        await p.screenshot(path='/tmp/v16_admin.png', full_page=True)
        await p.get_by_role('button', name='Start fresh…').click()
        await p.get_by_placeholder('Type START FRESH').fill('START FRESH')
        p.on('dialog', lambda d: asyncio.ensure_future(d.accept()))
        await p.get_by_role('button', name='Delete everything').click(); await p.wait_for_timeout(2500)
        print('back at login:', await p.get_by_role('button', name='Send OTP on WhatsApp').count(), [e for e in p.errs if '401' not in e and 'key" prop' not in e])
        await b.close()
asyncio.run(main())
